#!/usr/bin/env node
/**
 * Package representative agent trajectories into the top-level trajectories/
 * directory (submission deliverable #4): human-readable Markdown renderings
 * plus the raw JSONL, organized per stage/fixture, with an index.
 *
 * Usage: node stepfree/eval/package-trajectories.mjs <stage:fixture> [...]
 *   e.g. node stepfree/eval/package-trajectories.mjs baseline:08-shelter final:08-shelter final:11-venue
 */
import { readdirSync, mkdirSync, copyFileSync, writeFileSync, existsSync, rmSync, readFileSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderTrajectoryMarkdown } from '../src/lib/trajectory.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'trajectories');
const picks = process.argv.slice(2);
if (!picks.length) {
  console.error('usage: node stepfree/eval/package-trajectories.mjs <stage:fixture> [...]');
  process.exit(1);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const index = [
  '# Agent trajectories',
  '',
  'Every agent run in this project is captured as JSONL (one event per line: prompts, every tool call, every tool result, verification verdicts, retries, rollbacks) and rendered to Markdown for reading. The runs below are representative; the full set for every stage is regenerated by `stepfree/eval/run-all-stages.sh` under `runs/<stage>/<fixture>/trajectories/`.',
  '',
  '| Run | Agent | Files |',
  '|---|---|---|',
];

for (const pick of picks) {
  const [stage, fixture] = pick.split(':');
  const src = join(ROOT, 'runs', stage, fixture, 'trajectories');
  if (!existsSync(src)) {
    console.warn(`⚠ no trajectories at ${src}`);
    continue;
  }
  const destDir = join(OUT, `${stage}--${fixture}`);
  mkdirSync(destDir, { recursive: true });
  for (const f of readdirSync(src).filter((f) => f.endsWith('.jsonl'))) {
    copyFileSync(join(src, f), join(destDir, f));
    const md = f.replace(/\.jsonl$/, '.md');
    try {
      writeFileSync(join(destDir, md), renderTrajectoryMarkdown(join(src, f)));
    } catch (e) {
      console.warn(`render failed ${f}: ${e.message}`);
    }
    const agent = f.replace(/\.jsonl$/, '').split('-').slice(1).join('-') || f;
    index.push(`| ${stage} / ${fixture} | ${agent} | [${md}](./${stage}--${fixture}/${md}) ([raw](./${stage}--${fixture}/${f})) |`);
  }
  console.log(`packaged ${pick}`);
}

writeFileSync(join(OUT, 'README.md'), index.join('\n') + '\n');
console.log(`index → ${join(OUT, 'README.md')}`);
